/**
 * Java 字符串字面量转义（主进程侧）。
 *
 * 与 `src/renderer/src/lib/javaEscape.ts` 是**同一份规则的两处拷贝**：
 * 两边运行在不同进程（渲染进程 / 主进程），无法共享同一个模块实例，
 * 且渲染层那份是 UI 热路径、不希望主进程再引一层间接。
 *
 * 因此把「两份实现必须保持一致」变成可测的不变量：
 * `sandboxed-mustache.test.ts` 里有逐输入对照测试，任何一侧漂移都会红。
 *
 * 安全性：
 * - `"` 被转义为 `\"` 后，字段值无法闭合外层字符串字面量，
 *   所有内容都被视为字符串数据而非可执行代码。
 * - 反斜杠必须**先于**引号转义，否则 `\"` 会被错误地变成 `\\`
 *   （转义反斜杠 + 关闭引号），等于开了个口子。
 * - 不转义 `(` `)` `;` —— 它们在 Java 字符串字面量内是普通字符，
 *   加反斜杠反而生成非法转义序列 `\(` `\)` `\;` 导致编译失败。
 */

/** Java 字符串字面量转义：先转义反斜杠，再转义引号 + 换行/回车/Tab */
export function escapeJavaStringLiteral(s: string): string {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
}
